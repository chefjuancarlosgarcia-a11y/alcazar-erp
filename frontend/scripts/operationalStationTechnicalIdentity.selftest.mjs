import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")

function read(rel) {
  return fs.readFileSync(path.join(repoRoot, rel), "utf8")
}

const authCtx = read("frontend/src/context/AuthContext.jsx")
const protectedRoute = read("frontend/src/routes/ProtectedRoute.jsx")
const stationRoute = read("frontend/src/routes/StationDeviceRoute.jsx")
const edgeEnroll = read("supabase/functions/operational-station-enroll/index.ts")
const mig196 = read("supabase/schema/196_fix_operational_station_technical_identity.sql")
const pre196 = read("supabase/schema/diagnose_operational_station_technical_identity_preflight_196.sql")
const test196 = read("supabase/schema/196_test_operational_station_technical_identity.sql")

const tests = [
  {
    name: "TI-1 AuthContext checks technical identity before profiles",
    run() {
      const loadIdx = authCtx.indexOf("loadProfileForSession")
      const profilesIdx = authCtx.indexOf('from("profiles")')
      const candidateIdx = authCtx.indexOf("isOperationalStationDeviceSessionCandidate")
      const rpcIdx = authCtx.indexOf("get_operational_station_device_context")
      if (candidateIdx < 0 || rpcIdx < 0) throw new Error("candidate + RPC required")
      if (!(candidateIdx < profilesIdx && rpcIdx < profilesIdx)) {
        throw new Error("device path must precede profiles query")
      }
      if (!/app_metadata\?\.operational_station_device/.test(authCtx)) {
        throw new Error("app_metadata marker required")
      }
    }
  },
  {
    name: "TI-2 technical inactive denies without profiles fallback",
    run() {
      const block = authCtx.match(
        /isOperationalStationDeviceSessionCandidate[\s\S]*?const profileQuery/
      )?.[0]
      if (!block || /from\("profiles"\)/.test(block)) {
        throw new Error("technical branch must not query profiles")
      }
      if (!/station_device_denied/.test(authCtx)) throw new Error("deny outcome required")
    }
  },
  {
    name: "TI-3 ProtectedRoute blocks technical sessions",
    run() {
      if (!/isOperationalStationDeviceSessionCandidate/.test(protectedRoute)) {
        throw new Error("ProtectedRoute must reject technical session")
      }
      if (!/isStationDevice/.test(protectedRoute)) throw new Error("active device guard")
    }
  },
  {
    name: "TI-4 StationDeviceRoute requires active context",
    run() {
      if (!/stationDeviceContext\?\.active/.test(stationRoute)) {
        throw new Error("StationDeviceRoute active gate")
      }
    }
  },
  {
    name: "TI-5 Edge sets app_metadata and removes autogenerated profile",
    run() {
      if (!/app_metadata:\s*\{\s*operational_station_device:\s*true/.test(edgeEnroll)) {
        throw new Error("app_metadata server marker")
      }
      if (!/removeAutogeneratedTechnicalProfile/.test(edgeEnroll)) {
        throw new Error("profile cleanup helper")
      }
      if (!/technical_identity_mismatch/.test(edgeEnroll)) {
        throw new Error("must validate auth user + device id")
      }
      if (/station-device-.*delete|email.*like/i.test(edgeEnroll)) {
        throw new Error("must not delete profiles by email pattern")
      }
    }
  },
  {
    name: "TI-6 Edge compensates failed cleanup",
    run() {
      if (!/profileCleanup\.ok\)[\s\S]*deleteUser\(authUserId\)/.test(edgeEnroll)) {
        throw new Error("deleteUser on cleanup failure")
      }
      if (!/profile_cleanup_/.test(edgeEnroll)) throw new Error("fail enrollment reason")
    }
  },
  {
    name: "TI-7 no service_role in frontend",
    run() {
      if (/SERVICE_ROLE|service_role/.test(authCtx)) throw new Error("AuthContext service_role forbidden")
    }
  },
  {
    name: "TI-8 migration 196 links device auth_user_id not email",
    run() {
      if (!/operational_station_devices/.test(mig196)) throw new Error("device join required")
      if (/email\s+like\s+'%station-device%/i.test(mig196)) {
        throw new Error("email LIKE-only cleanup forbidden")
      }
      if (!/196_preflight_blocked/.test(mig196)) throw new Error("human blocker guard")
    }
  },
  {
    name: "TI-9 SQL test summary pattern",
    run() {
      if (!/begin;/.test(test196) || !/rollback;/.test(test196)) {
        throw new Error("test must use BEGIN/ROLLBACK")
      }
      if (!/count\(\*\) as total/.test(test196)) throw new Error("total/passed/failed summary")
    }
  },
  {
    name: "TI-10 preflight diagnose counts blockers",
    run() {
      if (!/human_blocker_profiles/.test(pre196)) throw new Error("blocker count")
      if (!/eligible_technical_profiles_with_auth_marker/.test(pre196)) {
        throw new Error("eligible count")
      }
    }
  }
]

let failed = 0
for (const t of tests) {
  try {
    t.run()
    console.log(`PASS ${t.name}`)
  } catch (err) {
    failed += 1
    console.error(`FAIL ${t.name}: ${err.message}`)
  }
}

if (failed > 0) process.exit(1)
console.log(`operationalStationTechnicalIdentity.selftest: ${tests.length} passed`)
